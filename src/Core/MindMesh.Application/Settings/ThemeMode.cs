namespace MindMesh.Application.Settings;

/// <summary>
/// Color theme of the application.
/// </summary>
public enum ThemeMode
{
	/// <summary>The light theme. The default.</summary>
	Light,

	Dark,

	/// <summary>Follows the theme of the operating system.</summary>
	System,

	/// <summary>Dark with deep blue surfaces.</summary>
	Midnight,

	/// <summary>Dark with green surfaces.</summary>
	Forest,

	/// <summary>Light with cool blue surfaces.</summary>
	Ocean,

	/// <summary>Light with warm rose surfaces.</summary>
	Rose,
}
